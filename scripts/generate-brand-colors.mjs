#!/usr/bin/env node
// Generator for the business colour code (docs/BRANDING.md §3.6, ledger BRAND-2).
// Source: contracts/brand-colors.yaml
// Outputs:
//   frontend/src/lib/badgeColors.generated.ts
//   mobile/lib/core/theme/enum_colors.generated.dart
//
// Only the *family* of each enum value is shared. How a family renders stays in each client:
// Mantine shades on the web, `PdlFamily` → `PdlColors` pairs in mobile/lib/core/theme/enum_colors.dart.

import { createRequire } from 'node:module'
import { fileURLToPath } from 'node:url'
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'

const scriptDir = path.dirname(fileURLToPath(import.meta.url))
const repoRoot = path.resolve(scriptDir, '..')
const frontendReq = createRequire(path.join(repoRoot, 'frontend', 'package.json'))
const YAML = frontendReq('yaml')
// The Mantine palettes are the web theme's (theme.ts only adds virtual aliases), so the default
// theme is where a `blue-6` gradient stop gets its hex for the mobile.
const { DEFAULT_THEME } = frontendReq('@mantine/core')

const STYLES = ['soft', 'filled']
const UNKNOWN_FAMILY = 'gray'

const outputs = {
  yaml: path.join(repoRoot, 'contracts', 'brand-colors.yaml'),
  openapi: path.join(repoRoot, 'contracts', 'openapi.json'),
  dartModels: path.join(repoRoot, 'mobile', 'lib', 'api', 'generated', 'models'),
  ts: path.join(repoRoot, 'frontend', 'src', 'lib', 'badgeColors.generated.ts'),
  dart: path.join(repoRoot, 'mobile', 'lib', 'core', 'theme', 'enum_colors.generated.dart'),
}

const snake = (name) => name.replace(/([a-z0-9])([A-Z])/g, '$1_$2').toLowerCase()
const constCase = (name) => snake(name).toUpperCase()
const lowerFirst = (name) => name[0].toLowerCase() + name.slice(1)

/** API value → Dart identifier, read from the Freezed enum so naming quirks never matter. */
function dartEnumIdentifiers(enumName) {
  const file = path.join(outputs.dartModels, `${snake(enumName)}.dart`)
  let source
  try {
    source = readFileSync(file, 'utf8')
  } catch {
    throw new Error(
      `${path.relative(repoRoot, file)} is missing: generate the mobile client first ` +
        '(regenerate.sh and check.sh do it before pnpm check — docs/LEDGER_*.md BRAND-5)',
    )
  }
  const ids = new Map()
  for (const m of source.matchAll(/@JsonValue\('([^']+)'\)\s*\n\s*(\w+)\(/g)) ids.set(m[1], m[2])
  if (ids.size === 0) throw new Error(`${file}: no @JsonValue found`)
  return ids
}

function mantineStop(stop, where) {
  const m = /^([a-z]+)-(\d)$/.exec(stop)
  const hex = m && DEFAULT_THEME.colors[m[1]]?.[Number(m[2])]
  if (!hex) throw new Error(`${where}: "${stop}" is not a Mantine shade (expected e.g. blue-6)`)
  return { color: m[1], shade: Number(m[2]), hex }
}

function load() {
  const raw = YAML.parse(readFileSync(outputs.yaml, 'utf8'))
  const schemas = JSON.parse(readFileSync(outputs.openapi, 'utf8')).components.schemas
  const families = raw.families
  if (!Array.isArray(families) || !families.includes(UNKNOWN_FAMILY)) {
    throw new Error(`families must be a list that includes ${UNKNOWN_FAMILY} (unknown values)`)
  }

  const enums = Object.entries(raw.enums ?? {}).map(([name, spec]) => {
    if (!STYLES.includes(spec.style)) {
      throw new Error(`enums.${name}: style must be one of ${STYLES.join(', ')}`)
    }
    const apiValues = schemas[name]?.enum
    if (!apiValues) throw new Error(`enums.${name}: no such enum in contracts/openapi.json`)
    const values = Object.entries(spec.values ?? {})
    for (const [value, family] of values) {
      if (!apiValues.includes(value)) throw new Error(`enums.${name}.${value}: not in the contract`)
      if (!families.includes(family)) {
        throw new Error(`enums.${name}.${value}: unknown family "${family}"`)
      }
    }
    const missing = apiValues.filter((v) => !(v in spec.values))
    if (missing.length) throw new Error(`enums.${name}: no family for ${missing.join(', ')}`)
    // Contract order, so a regenerated file only moves when the contract does.
    const ordered = apiValues.map((v) => [v, spec.values[v]])
    return { name, style: spec.style, values: ordered, dartIds: dartEnumIdentifiers(name) }
  })

  const gradients = Object.entries(raw.gradients ?? {}).map(([key, stops]) => {
    if (!Array.isArray(stops) || stops.length !== 2) {
      throw new Error(`gradients.${key}: expected two stops`)
    }
    return { key, stops: stops.map((s) => mantineStop(s, `gradients.${key}`)) }
  })

  return { families, enums, gradients }
}

function generateTs({ families, enums, gradients }) {
  const lines = [
    '// GENERATED by scripts/generate-brand-colors.mjs — edit contracts/brand-colors.yaml instead.',
    '// The family of each enum value (docs/BRANDING.md §3.6). How it renders is up to the component:',
    "// badges use Mantine's `light` variant, except where the series' variant says `filled`.",
    '',
    `import type { ${enums.map((e) => e.name).join(', ')} } from '@/api/dto'`,
    '',
    `export type BadgeFamily = ${families.map((f) => `'${f}'`).join(' | ')}`,
    '',
  ]
  for (const e of enums) {
    lines.push(`export const ${constCase(e.name)}_COLORS = {`)
    for (const [value, family] of e.values) lines.push(`  ${value}: '${family}',`)
    lines.push(`} as const satisfies Record<${e.name}, BadgeFamily>`)
    lines.push('')
  }
  lines.push('/** The Mantine badge variant of each series. */')
  lines.push('export const BADGE_VARIANTS = {')
  for (const e of enums) lines.push(`  ${e.name}: '${e.style === 'filled' ? 'filled' : 'light'}',`)
  lines.push('} as const')
  lines.push('')
  lines.push('/** Background of a card without a picture, 135° (top left → bottom right). */')
  lines.push('export const FALLBACK_GRADIENTS = {')
  for (const g of gradients) {
    const [from, to] = g.stops.map((s) => `var(--mantine-color-${s.color}-${s.shade})`)
    lines.push(`  ${g.key}: 'linear-gradient(135deg, ${from} 0%, ${to} 100%)',`)
  }
  lines.push('} as const')
  lines.push('')
  return lines.join('\n')
}

function generateDart({ families, enums, gradients }) {
  const lines = [
    '// GENERATED by scripts/generate-brand-colors.mjs — edit contracts/brand-colors.yaml instead.',
    '// ignore_for_file: type=lint',
    '',
    '// `Visibility` est à la fois un widget Flutter et un enum du contrat : ici',
    "// c'est l'enum qui compte.",
    "import 'package:flutter/painting.dart';",
    '',
    ...enums.map((e) => `import '../../api/generated/models/${snake(e.name)}.dart';`),
    "import 'enum_colors.dart';",
    "import 'pdl_colors.dart';",
    '',
    '/// Les familles du code couleur métier. Le rendu de chacune est écrit à la',
    '/// main dans `enum_colors.dart` (`PdlFamilyTone`).',
    `enum PdlFamily { ${families.join(', ')} }`,
    '',
  ]
  for (const e of enums) {
    lines.push(`extension ${e.name}Tone on ${e.name} {`)
    lines.push('  PdlFamily get family => switch (this) {')
    for (const [value, family] of e.values) {
      const id = e.dartIds.get(value)
      if (!id)
        throw new Error(`${e.name}.${value}: not in the generated Dart enum — run build_runner`)
      lines.push(`    ${e.name}.${id} => PdlFamily.${family},`)
    }
    lines.push(`    ${e.name}.$unknown => PdlFamily.${UNKNOWN_FAMILY},`)
    lines.push('  };')
    lines.push('')
    lines.push(`  PdlTone tone(PdlColors c) => family.${e.style}(c);`)
    lines.push('}')
    lines.push('')
  }
  lines.push("/// Fond d'une carte sans photo, à 135° (haut gauche → bas droite).")
  lines.push('abstract final class PdlFallbackGradients {')
  for (const g of gradients) {
    const colors = g.stops.map((s) => `Color(0xFF${s.hex.slice(1).toUpperCase()})`).join(', ')
    lines.push(`  static const LinearGradient ${lowerFirst(g.key.toLowerCase())} = LinearGradient(`)
    lines.push('    begin: Alignment.topLeft,')
    lines.push('    end: Alignment.bottomRight,')
    lines.push(`    colors: <Color>[${colors}],`)
    lines.push('  );')
  }
  lines.push('}')
  lines.push('')
  return lines.join('\n')
}

function writeIfChanged(target, content) {
  let prev = null
  try {
    prev = readFileSync(target, 'utf8')
  } catch {}
  if (prev === content) return false
  writeFileSync(target, content)
  return true
}

function main() {
  const model = load()
  const results = [
    [outputs.ts, generateTs(model)],
    [outputs.dart, generateDart(model)],
  ]
  for (const [target, content] of results) {
    const didWrite = writeIfChanged(target, content)
    const rel = path.relative(repoRoot, target)
    console.log(`${didWrite ? 'wrote ' : 'skip  '} ${rel}${didWrite ? '' : ' (unchanged)'}`)
  }
}

main()
